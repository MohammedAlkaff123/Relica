// Writes content/preload.json: every file the game needs, with its size, for the loading screen.
// Run after adding or changing assets:   node tools/make-preload.mjs
// The loading screen downloads exactly this list and shows real progress in bytes.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const groups = [
  ['code', ['src', 'vendor'], ['.js']],
  ['data', ['content'], ['.json']],
  ['models', ['public/models'], ['.glb']],
  ['textures', ['public/textures'], ['.jpg', '.png']],
  ['photos', ['public/nasa'], ['.jpg', '.json', '.csv']],
  ['fonts', ['public/brand/fonts'], ['.woff2', '.ttf']],
];
const skip = new Set(['content/preload.json', 'src/core/selftest.js']);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

const files = [];
for (const [group, dirs, exts] of groups) {
  for (const d of dirs) {
    for (const p of walk(join(root, d))) {
      const rel = relative(root, p).split('\\').join('/');
      if (skip.has(rel) || !exts.includes(extname(p).toLowerCase())) continue;
      files.push({ path: rel, bytes: statSync(p).size, group });
    }
  }
}
files.push({ path: 'style.css', bytes: statSync(join(root, 'style.css')).size, group: 'code' });
const total = files.reduce((s, f) => s + f.bytes, 0);
writeFileSync(join(root, 'content/preload.json'), JSON.stringify({ _readme: 'Generated by tools/make-preload.mjs. Do not edit by hand.', total, files }, null, 1) + '\n');
console.log(`${files.length} files, ${(total / 1048576).toFixed(1)} MB`);
